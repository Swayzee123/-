def gen(pid, pal, icon, name, sub):
    img = Image.new("RGBA", (SIZE, SIZE), (0,0,0,255))
    d = ImageDraw.Draw(img)
    bg, c1, c2, glow = pal["bg"], pal["c1"], pal["c2"], pal["glow"]
    
    for y in range(SIZE):
        r = y/SIZE
        cr = int(bg[0]*(1-r*0.3))
        cg = int(bg[1]*(1-r*0.3))
        cb = int(bg[2]+(20-bg[2])*r*0.3)
        d.line([(0,y),(SIZE,y)], fill=(cr,cg,cb,255))
    
    for gx in range(0,SIZE,PX*3):
        d.line([(gx,0),(gx,SIZE)], fill=(255,255,255,8), width=1)
    for gy in range(0,SIZE,PX*3):
        d.line([(0,gy),(SIZE,gy)], fill=(255,255,255,8), width=1)
    
    rng = random.Random(42)
    for _ in range(40):
        sx = rng.randint(0,SIZE-1)
        sy = rng.randint(0,SIZE-1)
        a = rng.randint(80,200)
        d.point((sx,sy), fill=(200,200,255,a))
        if rng.random() > 0.7:
            d.point((sx+1,sy), fill=(200,200,255,a//2))
            d.point((sx-1,sy), fill=(200,200,255,a//2))
    
    cx, cy = SIZE//2, SIZE//2-20
    for r in range(130,80,-2):
        a = int(15*(1-(r-80)/50))
        d.ellipse([cx-r,cy-r,cx+r,cy+r], outline=(*glow,a))
    
    ih = len(icon)
    iw = len(icon[0]) if ih else 0
    sx = (SIZE-iw*PX)//2
    sy = cy-(ih*PX)//2
    
    cmap = {"1":c1,"2":c2,"3":glow}
    for ri,row in enumerate(icon):
        for ci,cell in enumerate(row):
            if cell != "0":
                c = cmap.get(cell, c1)
                px_x = sx+ci*PX
                px_y = sy+ri*PX
                d.rectangle([px_x,px_y,px_x+PX-1,px_y+PX-1], fill=(*c,255))
                d.rectangle([px_x+1,px_y+1,px_x+2,px_y+2],
                    fill=(min(c[0]+40,255),min(c[1]+40,255),min(c[2]+40,255),180))
    
    rng2 = random.Random(hash(pid))
    sakura = (232,93,138)
    for _ in range(18):
        px = rng2.randint(10,SIZE-30)
        py = rng2.randint(10,SIZE-30)
        sz = rng2.choice([3,4,5,6])
        a = rng2.randint(100,200)
        d.rectangle([px,py,px+sz,py+sz], fill=(*sakura,a))
        d.rectangle([px+sz+1,py+sz//2,px+sz+2,py+sz//2+1], fill=(*sakura,a//2))
    
    for i in range(4):
        a = 180-i*50
        d.rectangle([i,i,SIZE-1-i,SIZE-1-i], outline=(*glow,max(a,0)))
    
    try:
        tf = ImageFont.truetype("arialbd.ttf", 22)
    except:
        try: tf = ImageFont.truetype("arial.ttf", 22)
        except: tf = ImageFont.load_default()
    
    bb = d.textbbox((0,0), name, font=tf)
    tw = bb[2]-bb[0]
    tx = (SIZE-tw)//2
    ty = SIZE-72
    d.text((tx+2,ty+2), name, fill=(0,0,0,200), font=tf)
    d.text((tx,ty), name, fill=(255,255,255,255), font=tf)
    
    try: sf = ImageFont.truetype("arial.ttf", 12)
    except: sf = ImageFont.load_default()
    bb2 = d.textbbox((0,0), sub, font=sf)
    sw = bb2[2]-bb2[0]
    d.text(((SIZE-sw)//2+1,SIZE-44+1), sub, fill=(0,0,0,160), font=sf)
    d.text(((SIZE-sw)//2,SIZE-44), sub, fill=(*glow,200), font=sf)
    
    try: wf = ImageFont.truetype("arial.ttf", 8)
    except: wf = ImageFont.load_default()
    wt = "MATCH SHOP"
    bb3 = d.textbbox((0,0), wt, font=wf)
    wtw = bb3[2]-bb3[0]
    d.text(((SIZE-wtw)//2,SIZE-18), wt, fill=(255,255,255,50), font=wf)
    
    return img

